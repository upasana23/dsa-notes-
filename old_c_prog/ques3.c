/*
 * Program 03: Basic Arithmetic Operations
 * Topic: Operators & Expressions
 */
#include <stdio.h>

int main(void) {
    int a = 15, b = 4;
    printf("a = %d, b = %d\n", a, b);
    printf("Sum: %d\n", a + b);
    printf("Difference: %d\n", a - b);
    printf("Product: %d\n", a * b);
    printf("Quotient: %d\n", a / b);
    printf("Remainder: %d\n", a % b);
    return 0;
}
